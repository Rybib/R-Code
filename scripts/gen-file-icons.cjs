// Generates src/renderer/src/lib/file-icons.gen.ts — a small subset of the MIT-licensed
// vscode-icons set (via @iconify-json/vscode-icons) for language badges on edits.
const fs = require('fs')
const j = require('@iconify-json/vscode-icons/icons.json')
const MAP = {
  swift: 'file-type-swift', py: 'file-type-python', pyi: 'file-type-python', ts: 'file-type-typescript', mts: 'file-type-typescript', cts: 'file-type-typescript',
  tsx: 'file-type-reactts', js: 'file-type-js', mjs: 'file-type-js', cjs: 'file-type-js', jsx: 'file-type-reactjs', rs: 'file-type-rust', go: 'file-type-go',
  json: 'file-type-json', md: 'file-type-markdown', mdx: 'file-type-markdown', css: 'file-type-css', scss: 'file-type-scss', html: 'file-type-html', htm: 'file-type-html',
  sh: 'file-type-shell', zsh: 'file-type-shell', bash: 'file-type-shell', java: 'file-type-java', kt: 'file-type-kotlin', kts: 'file-type-kotlin', c: 'file-type-c', h: 'file-type-c',
  cpp: 'file-type-cpp', cc: 'file-type-cpp', hpp: 'file-type-cpp', m: 'file-type-objectivec', mm: 'file-type-objectivec', cs: 'file-type-csharp', rb: 'file-type-ruby', php: 'file-type-php',
  yml: 'file-type-yaml', yaml: 'file-type-yaml', toml: 'file-type-toml', sql: 'file-type-sql', xml: 'file-type-xml', plist: 'file-type-xml', lua: 'file-type-lua', zig: 'file-type-zig',
  ex: 'file-type-elixir', exs: 'file-type-elixir', hs: 'file-type-haskell', scala: 'file-type-scala', r: 'file-type-r', graphql: 'file-type-graphql', gql: 'file-type-graphql',
  prisma: 'file-type-prisma', svelte: 'file-type-svelte', vue: 'file-type-vue', svg: 'file-type-svg', png: 'file-type-image', jpg: 'file-type-image', jpeg: 'file-type-image',
  gif: 'file-type-image', webp: 'file-type-image', txt: 'file-type-text', xcodeproj: 'file-type-xcode', pbxproj: 'file-type-xcode', xcworkspace: 'file-type-xcode', storyboard: 'file-type-xcode', xib: 'file-type-xcode'
}
const NAMES = { dockerfile: 'file-type-docker', 'package.json': 'file-type-npm', '.gitignore': 'file-type-git', 'tailwind.config.js': 'file-type-tailwind', 'vite.config.ts': 'file-type-vite', 'package.swift': 'file-type-swift' }
const used = new Set([...Object.values(MAP), ...Object.values(NAMES), 'default-file'])
const icons = {}
for (const n of used) {
  const ic = j.icons[n]
  if (!ic) continue
  icons[n] = { body: ic.body, width: ic.width ?? j.width ?? 16, height: ic.height ?? j.height ?? 16 }
}
const out = `// Generated by scripts/gen-file-icons.cjs from @iconify-json/vscode-icons (MIT). Do not edit.
export const FILE_ICONS: Record<string, { body: string; width: number; height: number }> = ${JSON.stringify(icons)}
export const EXT_ICON: Record<string, string> = ${JSON.stringify(MAP)}
export const NAME_ICON: Record<string, string> = ${JSON.stringify(NAMES)}
`
fs.writeFileSync('src/renderer/src/lib/file-icons.gen.ts', out)
console.log(Object.keys(icons).length, 'icons,', out.length, 'bytes')
