import { createServer, type IncomingMessage, type Server as HttpServer } from 'node:http'
import { randomBytes } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { Server } from '@modelcontextprotocol/sdk/server/index.js'
import { StreamableHTTPServerTransport } from '@modelcontextprotocol/sdk/server/streamableHttp.js'
import { CallToolRequestSchema, ListToolsRequestSchema } from '@modelcontextprotocol/sdk/types.js'
import type { AgentId } from '@shared/types'
import type { BridgeInfo } from './agents/base'
import { dataPath, getSettings } from './store'
import { getTool, toolsFor, type ToolDef, type ToolResult } from './tools/registry'

// R-Code's tool bridge: a loopback-only HTTP server (bearer-token protected) that serves
// every R-Code tool — delegation, built-in browser, iOS Simulator, web search — to agents:
//   • Claude Code and Codex → streamable-HTTP MCP at /mcp/<threadId>?agent=<id>
//   • built-in Pi           → the R-Code Pi extension (below), which calls POST /call

export interface ThreadInfo {
  isChild: boolean
}

const PI_EXTENSION = `// R-Code bridge extension for its built-in Pi agent (generated by R-Code; do not edit).
import { readFileSync } from "node:fs";

const modeFile = process.env.RCODE_PI_MODE_FILE;
const bridgeUrl = process.env.RCODE_BRIDGE_URL;
const bridgeToken = process.env.RCODE_BRIDGE_TOKEN;
const threadId = process.env.RCODE_THREAD_ID;
let tools = [];
try { tools = JSON.parse(process.env.RCODE_TOOLS || "[]"); } catch {}
const ours = new Set(tools.map((t) => t.name));

function mode() {
  try { return JSON.parse(readFileSync(modeFile, "utf8")).mode || "allowAll"; } catch { return "allowAll"; }
}

const MUTATING = new Set(["edit", "write"]);

export default function (pi) {
  // Pi itself never asks before acting; R-Code's permission modes are enforced here.
  pi.on("tool_call", async (event, ctx) => {
    const m = mode();
    const name = event.toolName;
    if (ours.has(name)) return;
    if (m === "allowAll" || m === "auto") return;
    const isEdit = MUTATING.has(name);
    const isBash = name === "bash";
    if (m === "plan" && isEdit) return { block: true, reason: "Plan mode: file changes are disabled. Propose the change instead." };
    const needsAsk = (m === "ask" && (isEdit || isBash)) || ((m === "acceptEdits" || m === "plan") && isBash);
    if (!needsAsk) return;
    const input = event.input || {};
    const title = isBash ? "Run command" : (name === "write" ? "Write " : "Edit ") + (input.path || "file");
    const ok = await ctx.ui.confirm(title, isBash ? String(input.command || "") : String(input.path || ""));
    if (!ok) return { block: true, reason: "The user declined this action." };
  });

  if (!bridgeUrl) return;
  for (const t of tools) {
    pi.registerTool({
      name: t.name,
      label: t.name.replace(/_/g, " "),
      description: t.description,
      parameters: t.schema,
      async execute(_id, params, signal) {
        const res = await fetch(bridgeUrl + "/call", {
          method: "POST",
          headers: { "content-type": "application/json", authorization: "Bearer " + bridgeToken },
          body: JSON.stringify({ threadId, agent: "pi", name: t.name, args: params || {} }),
          signal,
        });
        const json = await res.json();
        const content = [{ type: "text", text: json.text ?? "" }];
        if (json.image) content.push({ type: "image", data: json.image.data, mimeType: json.image.mimeType });
        return { content, details: {}, isError: !!json.isError };
      },
    });
  }
}
`

function readBody(req: IncomingMessage): Promise<any> {
  return new Promise((resolve, reject) => {
    let data = ''
    req.on('data', (c) => (data += c))
    req.on('end', () => {
      if (!data) return resolve(undefined)
      try {
        resolve(JSON.parse(data))
      } catch (e) {
        reject(e)
      }
    })
    req.on('error', reject)
  })
}

async function runTool(def: ToolDef, threadId: string, agent: AgentId, args: any): Promise<ToolResult> {
  try {
    return await def.run({ threadId, agent }, args ?? {})
  } catch (err: any) {
    return { text: `Error: ${err?.message ?? err}`, isError: true }
  }
}

function buildMcpServer(threadId: string, agent: AgentId, info: ThreadInfo): Server {
  const defs = toolsFor(agent, { isChild: info.isChild, settings: getSettings() })
  const server = new Server({ name: 'rcode', version: '0.1.0' }, { capabilities: { tools: {} } })
  server.setRequestHandler(ListToolsRequestSchema, async () => ({
    tools: defs.map((d) => ({ name: d.name, description: d.description, inputSchema: d.schema as any }))
  }))
  server.setRequestHandler(CallToolRequestSchema, async (req) => {
    const def = defs.find((d) => d.name === req.params.name)
    if (!def) return { content: [{ type: 'text', text: `Unknown tool ${req.params.name}` }], isError: true }
    const res = await runTool(def, threadId, agent, req.params.arguments)
    const content: any[] = [{ type: 'text', text: res.text }]
    if (res.image) content.push({ type: 'image', data: res.image.data, mimeType: res.image.mimeType })
    return { content, isError: !!res.isError }
  })
  return server
}

/** Tool definitions handed to the Pi extension through the environment. */
export function piToolsJson(isChild: boolean): string {
  return JSON.stringify(toolsFor('pi', { isChild, settings: getSettings() }).map((d) => ({ name: d.name, description: d.description, schema: d.schema })))
}

export async function startBridge(threadInfo: (threadId: string) => ThreadInfo): Promise<BridgeInfo & { server: HttpServer }> {
  const token = randomBytes(24).toString('hex')
  const extDir = dataPath('pi-extension')
  mkdirSync(extDir, { recursive: true })
  const piExtension = `${extDir}/rcode-bridge.ts`
  writeFileSync(piExtension, PI_EXTENSION)

  const server = createServer(async (req, res) => {
    try {
      if (req.headers.authorization !== `Bearer ${token}`) {
        res.writeHead(401).end('unauthorized')
        return
      }
      const url = new URL(req.url ?? '/', 'http://127.0.0.1')
      const mcpMatch = url.pathname.match(/^\/mcp\/([\w-]+)$/)
      if (mcpMatch) {
        if (req.method !== 'POST') {
          res.writeHead(405).end()
          return
        }
        const body = await readBody(req)
        const agent = (url.searchParams.get('agent') ?? 'claude') as AgentId
        const mcp = buildMcpServer(mcpMatch[1], agent, threadInfo(mcpMatch[1]))
        const transport = new StreamableHTTPServerTransport({ sessionIdGenerator: undefined, enableJsonResponse: true })
        res.on('close', () => {
          void transport.close()
          void mcp.close()
        })
        await mcp.connect(transport)
        await transport.handleRequest(req, res, body)
        return
      }
      if (url.pathname === '/call' && req.method === 'POST') {
        const body = (await readBody(req)) ?? {}
        const def = getTool(body.name)
        const result: ToolResult = def ? await runTool(def, body.threadId, body.agent ?? 'pi', body.args) : { text: `Unknown tool ${body.name}`, isError: true }
        res.writeHead(200, { 'content-type': 'application/json' }).end(JSON.stringify(result))
        return
      }
      res.writeHead(404).end('not found')
    } catch (err: any) {
      if (!res.headersSent) res.writeHead(500, { 'content-type': 'application/json' })
      res.end(JSON.stringify({ text: `R-Code error: ${err?.message ?? err}`, isError: true }))
    }
  })
  server.requestTimeout = 0
  server.headersTimeout = 0
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve))
  const port = (server.address() as any).port
  return { url: `http://127.0.0.1:${port}`, token, mcpScript: '', piExtension, nodeBinary: process.execPath, server }
}
